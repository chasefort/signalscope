import type { MonitorRequest, Report, Signal } from "./types";

const cite = (ids: number[]) => (ids?.length ? ` ${ids.map((i) => `[${i}]`).join("")}` : "");

/** Render a report + evidence list as portable Markdown for export. */
export function reportToMarkdown(req: MonitorRequest, report: Report, signals: Signal[]): string {
  const date = new Date().toISOString().slice(0, 10);
  const lines: string[] = [
    `# Market monitoring report — ${req.brand}`,
    ``,
    `*Generated by SignalScope on ${date}.*`,
    `*Competitors: ${req.competitors.join(", ") || "—"} · Category: ${req.category || "—"}*`,
    `*Objective: ${req.objective || "general monitoring"}*`,
    ``,
    `## Executive summary`,
    ``,
    report.executiveSummary,
    ``,
    `**Sentiment: ${report.sentiment.overall}.** ${report.sentiment.summary}`,
    ``,
    `## Key themes`,
    ``,
    ...report.themes.flatMap((t) => [`### ${t.title}`, ``, t.summary + cite(t.signalIds), ``]),
  ];

  if (report.competitorMoves.length) {
    lines.push(`## Competitor moves`, ``);
    for (const m of report.competitorMoves) {
      lines.push(`### ${m.competitor}`, ``, m.insight + cite(m.signalIds), ``, `**So what:** ${m.soWhat}`, ``);
    }
  }

  lines.push(`## Opportunities`, ``);
  for (const o of report.opportunities) {
    lines.push(
      `### ${o.title} (${o.priority} priority)`,
      ``,
      o.rationale + cite(o.signalIds),
      ``,
      `**Recommended action:** ${o.recommendedAction}`,
      ``
    );
  }

  if (report.risks.length) {
    lines.push(`## Risks & watch items`, ``);
    for (const r of report.risks) {
      lines.push(`- **${r.title}** — ${r.rationale}${cite(r.signalIds)}`);
    }
    lines.push(``);
  }

  lines.push(`## Recommended actions`, ``, `| Action | Owner | When |`, `| --- | --- | --- |`);
  for (const a of report.actions) {
    lines.push(`| ${a.action.replace(/\|/g, "/")}${cite(a.signalIds)} | ${a.owner} | ${a.timeframe} |`);
  }

  lines.push(``, `## Coverage notes`, ``, report.coverageNotes, ``, `## Sources`, ``);
  for (const s of signals) {
    lines.push(`${s.id}. [${s.title}](${s.url}) — ${s.outlet}${s.publishedAt ? `, ${s.publishedAt.slice(0, 10)}` : ""}`);
  }

  return lines.join("\n");
}
